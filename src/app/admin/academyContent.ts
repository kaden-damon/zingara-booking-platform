export function getAcademyArticleText(article: AcademyArticle) {
  return [
    article.title,
    article.category,
    article.purpose,
    article.whenToUse,
    ...article.keywords,
    ...article.howTo,
    ...article.tips,
    ...article.commonMistakes,
    ...article.related,
  ].join(" ");
}

export function getAcademyReadingTime(article: AcademyArticle) {
  const wordCount = getAcademyArticleText(article)
    .split(/\s+/)
    .filter(Boolean).length;

  return `${Math.max(1, Math.ceil(wordCount / 160))} min read`;
}

export function getAcademyArticleByTitle(title: string) {
  return academyArticles.find(
    (article) => article.title.toLowerCase() === title.toLowerCase(),
  );
}
